import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const exports = {};
vm.runInNewContext(ts.transpileModule(readFileSync("lib/admin/pagination.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports, URLSearchParams });
const documents = Array.from({ length: 17 }, (_, i) => i);
const covered = [1, 2, 3].flatMap(page => { const state = exports.paginationState(documents.length, String(page)); return documents.slice(state.start, state.end); });
assert.deepEqual(covered, documents);
assert.equal(exports.paginationState(17, "999").page, 3);
assert.equal(exports.paginationState(17, "-3").page, 1);
assert.equal(exports.paginationState(17, "2.8").page, 2);
assert.equal(exports.paginationState(0, "999").page, 1);
assert.equal(exports.paginationState(17, "invalid").page, 1);
const returnUrl = exports.adminListUrl(2, "SAT 읽기");
assert.equal(new URL(returnUrl, "http://localhost").searchParams.get("q"), "SAT 읽기");
assert.equal(exports.returnListUrl(returnUrl), returnUrl);
assert.equal(exports.returnListUrl("https://example.com"), "/admin");
assert.equal(exports.returnListUrl("//example.com"), "/admin");
assert.equal(exports.returnListUrl("/admin/write"), "/admin");
console.log("Pagination covers all documents once; invalid pages, encoded searches and safe list return passed.");
